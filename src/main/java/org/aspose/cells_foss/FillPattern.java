package org.aspose.cells_foss;

/**
 * Represents the fill pattern used in cell styling.
 */
public enum FillPattern {
    /** No fill pattern. */
    NONE,
    /** Solid fill. */
    SOLID,
    /** Medium gray fill. */
    MEDIUM_GRAY,
    /** Dark gray fill. */
    DARK_GRAY,
    /** 12.5% gray fill. */
    GRAY_125,
    /** 6.25% gray fill. */
    GRAY_0625,
    /** Dark horizontal fill. */
    DARK_HORIZONTAL,
    /** Dark vertical fill. */
    DARK_VERTICAL,
    /** Dark down fill. */
    DARK_DOWN,
    /** Dark up fill. */
    DARK_UP,
    /** Dark grid fill. */
    DARK_GRID,
    /** Dark trellis fill. */
    DARK_TRELLIS,
    /** Light horizontal fill. */
    LIGHT_HORIZONTAL,
    /** Light vertical fill. */
    LIGHT_VERTICAL,
    /** Light down fill. */
    LIGHT_DOWN,
    /** Light up fill. */
    LIGHT_UP,
    /** Light grid fill. */
    LIGHT_GRID,
    /** Light trellis fill. */
    LIGHT_TRELLIS
}
