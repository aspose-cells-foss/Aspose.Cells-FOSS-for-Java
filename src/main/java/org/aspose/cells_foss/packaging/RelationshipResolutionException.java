package org.aspose.cells_foss.packaging;

/**
 * Exception thrown when a relationship cannot be resolved in the package structure.
 */
public class RelationshipResolutionException extends PackageStructureException {
    /**
     * Initializes a new instance of the RelationshipResolutionException class.
     *
     * @param message the error message
     */
    public RelationshipResolutionException(String message) {
        super(message);
    }
}
