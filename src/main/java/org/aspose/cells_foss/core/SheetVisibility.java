package org.aspose.cells_foss.core;

/**
 * Represents the visibility state of a worksheet in an Excel workbook.
 */
public enum SheetVisibility {
    /** The sheet is visible. */
    VISIBLE,
    /** The sheet is hidden. */
    HIDDEN,
    /** The sheet is very hidden (hidden and cannot be unhidden through the Excel UI). */
    VERY_HIDDEN
}
