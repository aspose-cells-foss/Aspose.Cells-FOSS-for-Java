package org.aspose.cells_foss.core;

/**
 * Represents the pattern used to fill a cell.
 */
public enum FillPatternKind {
    /** No fill pattern. */
    NONE,
    /** Solid fill pattern. */
    SOLID,
    /** Medium gray fill pattern. */
    MEDIUM_GRAY,
    /** Dark gray fill pattern. */
    DARK_GRAY,
    /** Gray 12.5% fill pattern. */
    GRAY_125,
    /** Gray 6.25% fill pattern. */
    GRAY_0625,
    /** Dark horizontal fill pattern. */
    DARK_HORIZONTAL,
    /** Dark vertical fill pattern. */
    DARK_VERTICAL,
    /** Dark down diagonal fill pattern. */
    DARK_DOWN,
    /** Dark up diagonal fill pattern. */
    DARK_UP,
    /** Dark grid fill pattern. */
    DARK_GRID,
    /** Dark trellis fill pattern. */
    DARK_TRELLIS,
    /** Light horizontal fill pattern. */
    LIGHT_HORIZONTAL,
    /** Light vertical fill pattern. */
    LIGHT_VERTICAL,
    /** Light down diagonal fill pattern. */
    LIGHT_DOWN,
    /** Light up diagonal fill pattern. */
    LIGHT_UP,
    /** Light grid fill pattern. */
    LIGHT_GRID,
    /** Light trellis fill pattern. */
    LIGHT_TRELLIS
}
