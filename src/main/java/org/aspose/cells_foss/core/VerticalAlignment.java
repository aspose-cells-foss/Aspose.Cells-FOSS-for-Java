package org.aspose.cells_foss.core;

/**
 * Represents vertical alignment options for cell content.
 */
public enum VerticalAlignment {
    /** Align content to the bottom of the cell. */
    BOTTOM,
    /** Center content vertically in the cell. */
    CENTER,
    /** Align content to the top of the cell. */
    TOP,
    /** Justify content vertically, stretching to fill the cell height. */
    JUSTIFY,
    /** Distribute content evenly across the cell height. */
    DISTRIBUTED
}
