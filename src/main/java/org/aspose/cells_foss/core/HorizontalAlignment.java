package org.aspose.cells_foss.core;

/**
 * Represents horizontal alignment options for cell content in Excel.
 */
public enum HorizontalAlignment {
    /** General alignment (default). */
    GENERAL,
    /** Align content to the left. */
    LEFT,
    /** Center content. */
    CENTER,
    /** Align content to the right. */
    RIGHT,
    /** Fill content across the cell. */
    FILL,
    /** Justify content. */
    JUSTIFY,
    /** Center content continuously across merged cells. */
    CENTER_CONTINUOUS,
    /** Distribute content evenly. */
    DISTRIBUTED
}
