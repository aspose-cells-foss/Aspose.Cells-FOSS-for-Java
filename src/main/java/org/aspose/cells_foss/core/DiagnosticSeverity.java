package org.aspose.cells_foss.core;

/**
 * Represents the severity of a diagnostic entry.
 */
public enum DiagnosticSeverity {
    /** A warning diagnostic. */
    WARNING,
    /** A recoverable diagnostic. */
    RECOVERABLE,
    /** A lossy recoverable diagnostic. */
    LOSSY_RECOVERABLE,
    /** A fatal diagnostic. */
    FATAL
}
