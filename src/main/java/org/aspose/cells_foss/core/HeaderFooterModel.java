package org.aspose.cells_foss.core;

/**
 * Represents the header and footer model for a worksheet.
 */
public final class HeaderFooterModel {
    private String leftHeader;
    private String centerHeader;
    private String rightHeader;
    private String leftFooter;
    private String centerFooter;
    private String rightFooter;

    /**
     * Returns the left header.
     * @return the requested result
     */
    public String getLeftHeader() { return leftHeader; }
    /**
     * Sets the left header.
     * @param leftHeader left header
     */
    public void setLeftHeader(String leftHeader) { this.leftHeader = leftHeader; }

    /**
     * Returns the center header.
     * @return the requested result
     */
    public String getCenterHeader() { return centerHeader; }
    /**
     * Sets the center header.
     * @param centerHeader center header
     */
    public void setCenterHeader(String centerHeader) { this.centerHeader = centerHeader; }

    /**
     * Returns the right header.
     * @return the requested result
     */
    public String getRightHeader() { return rightHeader; }
    /**
     * Sets the right header.
     * @param rightHeader right header
     */
    public void setRightHeader(String rightHeader) { this.rightHeader = rightHeader; }

    /**
     * Returns the left footer.
     * @return the requested result
     */
    public String getLeftFooter() { return leftFooter; }
    /**
     * Sets the left footer.
     * @param leftFooter left footer
     */
    public void setLeftFooter(String leftFooter) { this.leftFooter = leftFooter; }

    /**
     * Returns the center footer.
     * @return the requested result
     */
    public String getCenterFooter() { return centerFooter; }
    /**
     * Sets the center footer.
     * @param centerFooter center footer
     */
    public void setCenterFooter(String centerFooter) { this.centerFooter = centerFooter; }

    /**
     * Returns the right footer.
     * @return the requested result
     */
    public String getRightFooter() { return rightFooter; }
    /**
     * Sets the right footer.
     * @param rightFooter right footer
     */
    public void setRightFooter(String rightFooter) { this.rightFooter = rightFooter; }
}
