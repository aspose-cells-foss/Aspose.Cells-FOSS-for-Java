package org.aspose.cells_foss;

/**
 * Thrown when an unsupported feature is encountered.
 */
public class UnsupportedFeatureException extends CellsException {
    /**
     * Initializes a new UnsupportedFeatureException instance.
     * @param message message
     */
    public UnsupportedFeatureException(String message) {
        super(message);
    }
}
