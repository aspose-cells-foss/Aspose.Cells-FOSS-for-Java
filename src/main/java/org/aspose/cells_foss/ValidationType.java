package org.aspose.cells_foss;

/**
 * Represents the type of cell validation.
 */
public enum ValidationType {
    /** Any value is allowed. */
    ANY_VALUE,
    /** Whole number validation. */
    WHOLE_NUMBER,
    /** Decimal validation. */
    DECIMAL,
    /** List validation. */
    LIST,
    /** Date validation. */
    DATE,
    /** Time validation. */
    TIME,
    /** Text length validation. */
    TEXT_LENGTH,
    /** Custom formula validation. */
    CUSTOM
}
