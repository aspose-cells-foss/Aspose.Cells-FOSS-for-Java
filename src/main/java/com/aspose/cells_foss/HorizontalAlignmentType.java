package com.aspose.cells_foss;

/**
 * Represents the type of horizontal alignment for cell content.
 */
public enum HorizontalAlignmentType {
    /** The general alignment. */
    GENERAL,
    /** Left alignment. */
    LEFT,
    /** Center alignment. */
    CENTER,
    /** Right alignment. */
    RIGHT,
    /** Fill alignment. */
    FILL,
    /** Justify alignment. */
    JUSTIFY,
    /** Center continuous alignment. */
    CENTER_CONTINUOUS,
    /** Distributed alignment. */
    DISTRIBUTED
}