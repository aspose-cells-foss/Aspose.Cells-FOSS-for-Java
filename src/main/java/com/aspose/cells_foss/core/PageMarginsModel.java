package com.aspose.cells_foss.core;

/**
 * Represents page margins for a worksheet in an Excel file.
 */
public final class PageMarginsModel {
    private double left = 0.7;
    private double right = 0.7;
    private double top = 0.75;
    private double bottom = 0.75;
    private double header = 0.3;
    private double footer = 0.3;

    /**
     * Returns the left.
     * @return the requested result
     */
    public double getLeft() { return left; }
    /**
     * Sets the left.
     * @param left left
     */
    public void setLeft(double left) { this.left = left; }

    /**
     * Returns the right.
     * @return the requested result
     */
    public double getRight() { return right; }
    /**
     * Sets the right.
     * @param right right
     */
    public void setRight(double right) { this.right = right; }

    /**
     * Returns the top.
     * @return the requested result
     */
    public double getTop() { return top; }
    /**
     * Sets the top.
     * @param top top
     */
    public void setTop(double top) { this.top = top; }

    /**
     * Returns the bottom.
     * @return the requested result
     */
    public double getBottom() { return bottom; }
    /**
     * Sets the bottom.
     * @param bottom bottom
     */
    public void setBottom(double bottom) { this.bottom = bottom; }

    /**
     * Returns the header.
     * @return the requested result
     */
    public double getHeader() { return header; }
    /**
     * Sets the header.
     * @param header header
     */
    public void setHeader(double header) { this.header = header; }

    /**
     * Returns the footer.
     * @return the requested result
     */
    public double getFooter() { return footer; }
    /**
     * Sets the footer.
     * @param footer footer
     */
    public void setFooter(double footer) { this.footer = footer; }
}