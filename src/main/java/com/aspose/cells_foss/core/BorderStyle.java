package com.aspose.cells_foss.core;

/**
 * Represents the style of a border line in a cell.
 */
public enum BorderStyle {
    /** No border. */
    NONE,
    /** Thin border. */
    THIN,
    /** Medium border. */
    MEDIUM,
    /** Thick border. */
    THICK,
    /** Dotted border. */
    DOTTED,
    /** Dashed border. */
    DASHED,
    /** Double border. */
    DOUBLE,
    /** Hair-thin border. */
    HAIR,
    /** Medium dashed border. */
    MEDIUM_DASHED,
    /** Dash-dot border. */
    DASH_DOT,
    /** Medium dash-dot border. */
    MEDIUM_DASH_DOT,
    /** Dash-dot-dot border. */
    DASH_DOT_DOT,
    /** Medium dash-dot-dot border. */
    MEDIUM_DASH_DOT_DOT,
    /** Slanted dash-dot border. */
    SLANTED_DASH_DOT
}