package com.aspose.cells_foss;

/**
 * Represents the type of a cell value.
 */
public enum CellValueType {
    /** The cell is blank. */
    BLANK,
    /** The cell contains a string. */
    STRING,
    /** The cell contains a number. */
    NUMBER,
    /** The cell contains a boolean value. */
    BOOLEAN,
    /** The cell contains a date/time value. */
    DATE_TIME,
    /** The cell contains a formula. */
    FORMULA
}